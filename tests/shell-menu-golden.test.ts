// The whole menu, written out: every label, every key, every separator, every submenu and every standard item, in order, for each platform. The other tests of the menu compare it with the list of
// commands (so that a wrong word or key in the list cannot be seen from them); this one is a second source of truth, written by a person who read it: a word, a key or a place that changes shows here,
// and has to be changed here on purpose. (Review of the execution, 22 October 2026: five changes of the menu, in a key, a word and the order of items, that no other test noticed.)
const FLAGS: Flags = { theme: 'system', toolbar: true, fullscreen: false, prompt: false };
const line = (e: Entry): string => e.kind === 'separator' ? '-' : e.kind === 'submenu' ? e.label + ' >' : e.kind === 'role' ? e.label + ' <' + e.role + '>' : e.kind === 'plain' ? e.label + ' (plain)'
  : e.label + (e.accelerator ? ' [' + e.accelerator + ']' : '') + (e.control ? ' (' + e.control + ')' : '') + (e.hidden ? ' (hidden)' : '');      // 02-B3b: the places of the recent documents that there is none for
const walk = (items: readonly Entry[], depth: number): string[] => items.flatMap((e) => ['  '.repeat(depth) + line(e), ...(e.kind === 'submenu' ? walk(e.items, depth + 1) : [])]);
const written = (platform: 'darwin' | 'win32' | 'linux') => walk(buildMenu({ platform, appName: 'Remote Workspace', report: EMPTY_REPORT, flags: FLAGS }), 0);

